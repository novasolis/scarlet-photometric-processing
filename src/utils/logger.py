"""
Application logging utilities.

Centralises logging configuration for the photometric analysis
framework and provides module-specific loggers.

Third-party logging policies are also centralised here so that noisy
dependency loggers do not overwhelm the application output while
warnings and errors remain visible.

Application output is written simultaneously to:

    1. the terminal
    2. results/logs/main.log

The run log is overwritten when a new application process configures
logging, providing a clean record for each main workflow execution.
"""

from __future__ import annotations

import logging
import warnings
from pathlib import Path

from astropy.wcs import FITSFixedWarning


# ---------------------------------------------------------------------------
# Framework-wide logging defaults
# ---------------------------------------------------------------------------

DEFAULT_LOGGING_LEVEL = logging.INFO

DEFAULT_LOG_FORMAT = (
    "%(asctime)s | %(levelname)-8s | "
    "%(name)s | %(message)s"
)

DEFAULT_DATE_FORMAT = "%Y-%m-%d %H:%M:%S"


# ---------------------------------------------------------------------------
# Run-log configuration
# ---------------------------------------------------------------------------

# logger.py:
#
#     <project_root>
#         └── src
#             └── utils
#                 └── logger.py
#
# Therefore parents[2] resolves to the project root.

PROJECT_DIRECTORY = Path(__file__).resolve().parents[2]

RUN_LOG_DIRECTORY = (
    PROJECT_DIRECTORY
    / "results"
    / "logs"
)

RUN_LOG_PATH = (
    RUN_LOG_DIRECTORY
    / "main.log"
)

# Internal marker used to identify the framework's file handler.
FILE_HANDLER_MARKER = "_photometry_run_log"


# ---------------------------------------------------------------------------
# Third-party logger policies
# ---------------------------------------------------------------------------

"""
Astropy can emit informational messages when an NDData uncertainty
object does not expose the expected ``uncertainty_type`` attribute.

The message is harmless for the current photometric workflow but can
be emitted repeatedly while constructing TESS cadence Observations.

The Astropy logger hierarchy is therefore configured at WARNING so
that:

    DEBUG / INFO
        suppressed

    WARNING / ERROR / CRITICAL
        preserved

This policy intentionally applies to the Astropy logging hierarchy
rather than only ``astropy.nddata.nddata`` because the emitted record
can also be handled by the parent ``astropy`` logger.

FITS-related warnings such as FITSFixedWarning are Python warnings
rather than normal logging records. ``logging.captureWarnings(True)``
below routes those warnings through the logging framework so they are
also written to the application run log.

A small number of known FITS/WCS compatibility warnings generated by
legacy survey FITS headers are intentionally suppressed separately.
Only those specific messages are filtered; other FITSFixedWarning
messages remain visible.
"""

ASTROPY_LOGGER_NAMES: tuple[str, ...] = (
    "astropy",
    "astropy.nddata",
    "astropy.nddata.nddata",
)

ASTROPY_MINIMUM_LEVEL = logging.WARNING


# ---------------------------------------------------------------------------
# Known non-actionable Astropy warnings
# ---------------------------------------------------------------------------

"""
Certain FITS files, particularly legacy SDSS datasets, contain valid
but deprecated FITS/WCS metadata.

Astropy normalises this metadata and can emit messages such as:

    RADECSYS= 'ICRS ' / International Celestial Ref. System
    the RADECSYS keyword is deprecated, use RADESYSa.

and:

    'datfix' made the change
    'Set MJD-OBS to ... from DATE-OBS'.

These messages indicate Astropy's normalisation of legacy metadata.
They do not indicate a failure in:

    - FITS loading
    - WCS construction
    - source detection
    - aperture photometry
    - analysis

They are therefore suppressed at the warning level.

IMPORTANT:
Only these two known message patterns are suppressed.

Other FITSFixedWarning messages remain visible and can still identify
unexpected FITS/WCS problems.
"""

# ``warnings.filterwarnings(message=...)`` matches the beginning of the
# warning message, so the patterns intentionally describe only the stable
# portion of each Astropy message.

KNOWN_FITS_WARNING_MESSAGE_PATTERNS: tuple[str, ...] = (
    r"RADECSYS=.*the RADECSYS keyword is deprecated, use RADESYSa\.",
    r"'datfix' made the change 'Set MJD-OBS .* from DATE-OBS'\.",
)


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------


def _build_formatter() -> logging.Formatter:
    """
    Build the framework-wide logging formatter.
    """

    return logging.Formatter(
        fmt=DEFAULT_LOG_FORMAT,
        datefmt=DEFAULT_DATE_FORMAT,
    )


def _get_file_handler() -> logging.Handler | None:
    """
    Return the framework-managed run-log handler if one exists.

    Returns
    -------
    logging.Handler | None
        The existing application file handler, otherwise None.
    """

    root_logger = logging.getLogger()

    for handler in root_logger.handlers:
        if getattr(
            handler,
            FILE_HANDLER_MARKER,
            False,
        ):
            return handler

    return None


def _get_console_handler() -> logging.Handler | None:
    """
    Return the framework-managed console handler if one exists.

    Returns
    -------
    logging.Handler | None
        The existing application console handler, otherwise None.
    """

    root_logger = logging.getLogger()

    for handler in root_logger.handlers:
        if getattr(
            handler,
            "_photometry_console_log",
            False,
        ):
            return handler

    return None


def _create_file_handler() -> logging.Handler:
    """
    Create the application run-log file handler.

    The log file is opened in write mode so that a new application
    process starts with a clean log.

    Returns
    -------
    logging.Handler
        Configured file handler.
    """

    RUN_LOG_DIRECTORY.mkdir(
        parents=True,
        exist_ok=True,
    )

    file_handler = logging.FileHandler(
        filename=RUN_LOG_PATH,
        mode="w",
        encoding="utf-8",
    )

    setattr(
        file_handler,
        FILE_HANDLER_MARKER,
        True,
    )

    file_handler.setFormatter(
        _build_formatter(),
    )

    return file_handler


def _create_console_handler() -> logging.Handler:
    """
    Create the application terminal handler.

    Returns
    -------
    logging.Handler
        Configured console handler.
    """

    console_handler = logging.StreamHandler()

    setattr(
        console_handler,
        "_photometry_console_log",
        True,
    )

    console_handler.setFormatter(
        _build_formatter(),
    )

    return console_handler


def _configure_application_handlers(
    level: int,
) -> None:
    """
    Ensure the application console and file handlers exist.

    Existing framework-managed handlers are reused so that repeated
    calls to configure_logging() do not create duplicate log records.

    The run-log file is recreated in write mode when logging is first
    configured for a new process.
    """

    root_logger = logging.getLogger()

    formatter = _build_formatter()

    # -----------------------------------------------------------------------
    # Console handler
    # -----------------------------------------------------------------------

    console_handler = _get_console_handler()

    if console_handler is None:
        console_handler = _create_console_handler()

        root_logger.addHandler(
            console_handler,
        )

    else:
        console_handler.setFormatter(
            formatter,
        )

    console_handler.setLevel(
        level,
    )

    # -----------------------------------------------------------------------
    # Run file handler
    # -----------------------------------------------------------------------

    file_handler = _get_file_handler()

    if file_handler is None:
        file_handler = _create_file_handler()

        root_logger.addHandler(
            file_handler,
        )

    else:
        file_handler.setFormatter(
            formatter,
        )

    file_handler.setLevel(
        level,
    )


def _configure_warning_capture() -> None:
    """
    Route Python warnings through the logging framework.

    This allows warnings emitted by Astropy and other dependencies to
    appear in both the terminal and the run log.

    The operation is idempotent.

    Known, non-actionable Astropy FITS/WCS compatibility warnings are
    filtered separately by _configure_known_astropy_warnings().
    """

    logging.captureWarnings(
        True,
    )

    warnings_logger = logging.getLogger(
        "py.warnings",
    )

    # Allow warnings to reach the application root handlers.
    warnings_logger.propagate = True

    # Python warnings are warnings by definition. Keep them visible
    # unless they are explicitly filtered by a warning policy.
    warnings_logger.setLevel(
        logging.WARNING,
    )


def _configure_known_astropy_warnings() -> None:
    """
    Suppress only known, non-actionable Astropy FITS/WCS warnings.

    These warnings are generated when Astropy normalises legacy FITS
    metadata. They are expected for some survey datasets and do not
    indicate a processing failure.

    Only the explicitly listed message patterns are suppressed.

    Other FITSFixedWarning messages remain visible.
    """

    for message_pattern in KNOWN_FITS_WARNING_MESSAGE_PATTERNS:
        warnings.filterwarnings(
            "ignore",
            message=message_pattern,
            category=FITSFixedWarning,
        )


def _configure_third_party_loggers() -> None:
    """
    Apply framework-wide policies to noisy third-party loggers.

    This function is intentionally idempotent and may be called each
    time application logging is configured.

    Only the specified dependency loggers are modified.
    Application loggers are not affected.
    """

    for logger_name in ASTROPY_LOGGER_NAMES:
        third_party_logger = logging.getLogger(
            logger_name,
        )

        third_party_logger.setLevel(
            ASTROPY_MINIMUM_LEVEL,
        )

        # Preserve normal propagation to the application root handlers
        # for WARNING and more severe records.
        third_party_logger.propagate = True


def _apply_handler_levels(
    level: int,
) -> None:
    """
    Apply the requested application level to existing root handlers.

    Framework-managed handlers are updated directly. Other existing
    handlers are also updated to preserve the behaviour of the
    previous logging implementation.
    """

    root_logger = logging.getLogger()

    for handler in root_logger.handlers:
        handler.setLevel(
            level,
        )


# ---------------------------------------------------------------------------
# Public configuration API
# ---------------------------------------------------------------------------


def configure_logging(
    level: int = DEFAULT_LOGGING_LEVEL,
) -> None:
    """
    Configure application-wide logging.

    This function is safe to call multiple times.

    The first configuration creates:

        - a console handler
        - a run-log file handler

    The run-log file is:

        results/logs/main.log

    The file handler uses write mode so a fresh application process
    starts with a clean run log.

    Python warnings are captured and routed through the logging
    framework so warnings are recorded alongside normal application
    messages.

    Known non-actionable Astropy FITS/WCS warnings are filtered without
    suppressing other warnings.

    Third-party logging policies are applied after the root
    configuration so dependency-specific verbosity remains controlled
    independently of the application-wide level.

    Parameters
    ----------
    level
        Root logging level.
    """

    root_logger = logging.getLogger()

    # -----------------------------------------------------------------------
    # Root logger
    # -----------------------------------------------------------------------

    root_logger.setLevel(
        level,
    )

    # -----------------------------------------------------------------------
    # Application handlers
    # -----------------------------------------------------------------------

    _configure_application_handlers(
        level,
    )

    # -----------------------------------------------------------------------
    # Python warning capture
    # -----------------------------------------------------------------------

    _configure_warning_capture()

    # -----------------------------------------------------------------------
    # Known warning policies
    # -----------------------------------------------------------------------

    _configure_known_astropy_warnings()

    # -----------------------------------------------------------------------
    # Third-party logger policies
    # -----------------------------------------------------------------------

    _configure_third_party_loggers()


def set_logging_level(
    level: int,
) -> None:
    """
    Change the application-wide logging level.

    Parameters
    ----------
    level
        New root logging level.

    Notes
    -----
    Existing handlers are preserved.

    Third-party logger policies remain in effect. In particular,
    Astropy INFO and DEBUG records remain suppressed even when the
    application root logger is changed to DEBUG.

    Known Astropy FITS/WCS compatibility warnings remain filtered.
    Other warnings remain visible.
    """

    root_logger = logging.getLogger()

    root_logger.setLevel(
        level,
    )

    _apply_handler_levels(
        level,
    )

    _configure_warning_capture()
    _configure_known_astropy_warnings()
    _configure_third_party_loggers()


def get_logger(
    name: str,
) -> logging.Logger:
    """
    Return a configured logger.

    Parameters
    ----------
    name
        Logger name, typically ``__name__``.

    Returns
    -------
    logging.Logger
        Configured logger instance.

    Notes
    -----
    Calling ``get_logger()`` must not reset an explicitly selected
    application logging level.

    If logging has not yet been configured, the framework default
    logging configuration is created at ``DEFAULT_LOGGING_LEVEL``.

    When logging has already been configured, the existing application
    level is preserved while third-party logger and warning policies
    are refreshed.
    """

    root_logger = logging.getLogger()

    if not root_logger.handlers:
        configure_logging(
            DEFAULT_LOGGING_LEVEL,
        )

    else:
        # Ensure dependency-specific policies remain active without
        # changing the application's selected root logging level.
        _configure_warning_capture()
        _configure_known_astropy_warnings()
        _configure_third_party_loggers()

    return logging.getLogger(
        name,
    )